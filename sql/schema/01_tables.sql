-- =============================================================================
-- FreshMart schema: tables, constraints, indexes
-- Compatible with: Oracle Database 19c, 21c, 23ai, 26ai  (identity columns: 12.1+)
-- Run as the schema owner (for example FRESHMART) in a PDB, never as SYS.
-- NOT EXECUTED in the build environment of this repository: review before use.
-- =============================================================================

-- ---------- Reference / master data -----------------------------------------

CREATE TABLE categories (
    category_id        NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    category_name      VARCHAR2(100) NOT NULL,
    parent_category_id NUMBER(10),
    created_at         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_categories_name UNIQUE (category_name),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_category_id)
        REFERENCES categories (category_id)
);

CREATE TABLE suppliers (
    supplier_id   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    supplier_name VARCHAR2(150) NOT NULL,
    contact_email VARCHAR2(255) NOT NULL,
    phone         VARCHAR2(20),
    city          VARCHAR2(100) NOT NULL,
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_suppliers PRIMARY KEY (supplier_id),
    CONSTRAINT uq_suppliers_email UNIQUE (contact_email)
);

CREATE TABLE products (
    product_id      NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    sku             VARCHAR2(30)  NOT NULL,
    product_name    VARCHAR2(200) NOT NULL,
    category_id     NUMBER(10)    NOT NULL,
    supplier_id     NUMBER(10)    NOT NULL,
    unit_price      NUMBER(10,2)  NOT NULL,
    unit_of_measure VARCHAR2(20)  NOT NULL,
    is_active       CHAR(1)       DEFAULT 'Y' NOT NULL,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id)
        REFERENCES categories (category_id),
    CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id)
        REFERENCES suppliers (supplier_id),
    CONSTRAINT ck_products_price CHECK (unit_price > 0),
    CONSTRAINT ck_products_active CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE warehouses (
    warehouse_id   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    warehouse_name VARCHAR2(100) NOT NULL,
    city           VARCHAR2(100) NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_warehouses PRIMARY KEY (warehouse_id),
    CONSTRAINT uq_warehouses_name UNIQUE (warehouse_name)
);

CREATE TABLE employees (
    employee_id   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    employee_name VARCHAR2(150) NOT NULL,
    email         VARCHAR2(255) NOT NULL,
    job_title     VARCHAR2(100) NOT NULL,
    manager_id    NUMBER(10),
    warehouse_id  NUMBER(10),
    hire_date     DATE          NOT NULL,
    salary        NUMBER(10,2)  NOT NULL,
    CONSTRAINT pk_employees PRIMARY KEY (employee_id),
    CONSTRAINT uq_employees_email UNIQUE (email),
    CONSTRAINT fk_employees_manager FOREIGN KEY (manager_id)
        REFERENCES employees (employee_id),
    CONSTRAINT fk_employees_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES warehouses (warehouse_id),
    CONSTRAINT ck_employees_salary CHECK (salary > 0)
);

-- ---------- Customers --------------------------------------------------------

CREATE TABLE customers (
    customer_id   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    customer_name VARCHAR2(150) NOT NULL,
    email         VARCHAR2(255) NOT NULL,
    phone         VARCHAR2(20),
    city          VARCHAR2(100) NOT NULL,
    status        VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
    registered_on DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    row_version   NUMBER(10)    DEFAULT 0 NOT NULL,
    created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_customers PRIMARY KEY (customer_id),
    CONSTRAINT uq_customers_email UNIQUE (email),
    CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'BLOCKED'))
);

CREATE TABLE addresses (
    address_id   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    customer_id  NUMBER(10)    NOT NULL,
    address_type VARCHAR2(10)  DEFAULT 'HOME' NOT NULL,
    line1        VARCHAR2(200) NOT NULL,
    city         VARCHAR2(100) NOT NULL,
    state        VARCHAR2(100) NOT NULL,
    pincode      VARCHAR2(10)  NOT NULL,
    is_default   CHAR(1)       DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_addresses PRIMARY KEY (address_id),
    CONSTRAINT fk_addresses_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id) ON DELETE CASCADE,
    CONSTRAINT ck_addresses_type CHECK (address_type IN ('HOME', 'OFFICE', 'OTHER')),
    CONSTRAINT ck_addresses_default CHECK (is_default IN ('Y', 'N'))
);

-- ---------- Inventory --------------------------------------------------------

CREATE TABLE inventory (
    warehouse_id  NUMBER(10) NOT NULL,
    product_id    NUMBER(10) NOT NULL,
    qty_on_hand   NUMBER(10) DEFAULT 0 NOT NULL,
    qty_reserved  NUMBER(10) DEFAULT 0 NOT NULL,
    reorder_level NUMBER(10) DEFAULT 0 NOT NULL,
    row_version   NUMBER(10) DEFAULT 0 NOT NULL,
    updated_at    TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_inventory PRIMARY KEY (warehouse_id, product_id),
    CONSTRAINT fk_inventory_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES warehouses (warehouse_id),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id)
        REFERENCES products (product_id),
    CONSTRAINT ck_inventory_on_hand CHECK (qty_on_hand >= 0),
    CONSTRAINT ck_inventory_reserved CHECK (qty_reserved >= 0 AND qty_reserved <= qty_on_hand)
);

CREATE TABLE stock_movements (
    movement_id    NUMBER(12)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    warehouse_id   NUMBER(10)   NOT NULL,
    product_id     NUMBER(10)   NOT NULL,
    movement_type  VARCHAR2(12) NOT NULL,
    quantity       NUMBER(10)   NOT NULL,
    reference_type VARCHAR2(20),
    reference_id   NUMBER(12),
    moved_at       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_stock_movements PRIMARY KEY (movement_id),
    CONSTRAINT fk_stock_mov_inventory FOREIGN KEY (warehouse_id, product_id)
        REFERENCES inventory (warehouse_id, product_id),
    CONSTRAINT ck_stock_mov_type CHECK (movement_type IN ('RECEIPT', 'SALE', 'RETURN', 'ADJUSTMENT')),
    CONSTRAINT ck_stock_mov_qty CHECK (quantity <> 0)
);

-- ---------- Carts ------------------------------------------------------------

CREATE TABLE carts (
    cart_id     NUMBER(12)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    customer_id NUMBER(10)   NOT NULL,
    status      VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    created_at  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_carts PRIMARY KEY (cart_id),
    CONSTRAINT fk_carts_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id),
    CONSTRAINT ck_carts_status CHECK (status IN ('ACTIVE', 'CONVERTED', 'ABANDONED'))
);

CREATE TABLE cart_items (
    cart_id    NUMBER(12) NOT NULL,
    product_id NUMBER(10) NOT NULL,
    quantity   NUMBER(5)  NOT NULL,
    added_at   TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cart_items PRIMARY KEY (cart_id, product_id),
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id)
        REFERENCES carts (cart_id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id)
        REFERENCES products (product_id),
    CONSTRAINT ck_cart_items_qty CHECK (quantity > 0)
);

-- ---------- Promotions -------------------------------------------------------

CREATE TABLE promotions (
    promotion_id   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    promotion_name VARCHAR2(100) NOT NULL,
    discount_type  VARCHAR2(10)  NOT NULL,
    discount_value NUMBER(10,2)  NOT NULL,
    start_date     DATE          NOT NULL,
    end_date       DATE          NOT NULL,
    CONSTRAINT pk_promotions PRIMARY KEY (promotion_id),
    CONSTRAINT ck_promotions_type CHECK (discount_type IN ('PERCENT', 'FLAT')),
    CONSTRAINT ck_promotions_value CHECK (discount_value > 0),
    CONSTRAINT ck_promotions_dates CHECK (end_date >= start_date)
);

CREATE TABLE coupons (
    coupon_id        NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    coupon_code      VARCHAR2(30) NOT NULL,
    promotion_id     NUMBER(10)   NOT NULL,
    min_order_amount NUMBER(10,2) DEFAULT 0 NOT NULL,
    max_uses         NUMBER(10)   NOT NULL,
    used_count       NUMBER(10)   DEFAULT 0 NOT NULL,
    valid_from       DATE         NOT NULL,
    valid_to         DATE         NOT NULL,
    is_active        CHAR(1)      DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_coupons PRIMARY KEY (coupon_id),
    CONSTRAINT uq_coupons_code UNIQUE (coupon_code),
    CONSTRAINT fk_coupons_promotion FOREIGN KEY (promotion_id)
        REFERENCES promotions (promotion_id),
    CONSTRAINT ck_coupons_uses CHECK (used_count >= 0 AND used_count <= max_uses),
    CONSTRAINT ck_coupons_active CHECK (is_active IN ('Y', 'N'))
);

-- ---------- Orders -----------------------------------------------------------

CREATE TABLE orders (
    order_id        NUMBER(12)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    customer_id     NUMBER(10)   NOT NULL,
    address_id      NUMBER(10)   NOT NULL,
    warehouse_id    NUMBER(10)   NOT NULL,
    coupon_id       NUMBER(10),
    order_date      DATE         DEFAULT SYSDATE NOT NULL,
    status          VARCHAR2(12) DEFAULT 'PLACED' NOT NULL,
    subtotal        NUMBER(12,2) NOT NULL,
    discount_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
    delivery_fee    NUMBER(8,2)  DEFAULT 0 NOT NULL,
    total_amount    NUMBER(12,2) NOT NULL,
    created_at      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id),
    CONSTRAINT fk_orders_address FOREIGN KEY (address_id)
        REFERENCES addresses (address_id),
    CONSTRAINT fk_orders_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES warehouses (warehouse_id),
    CONSTRAINT fk_orders_coupon FOREIGN KEY (coupon_id)
        REFERENCES coupons (coupon_id),
    CONSTRAINT ck_orders_status CHECK (status IN ('PLACED', 'PACKED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND discount_amount >= 0 AND delivery_fee >= 0),
    CONSTRAINT ck_orders_total CHECK (total_amount = subtotal - discount_amount + delivery_fee)
);

CREATE TABLE order_items (
    order_id   NUMBER(12)   NOT NULL,
    line_no    NUMBER(4)    NOT NULL,
    product_id NUMBER(10)   NOT NULL,
    quantity   NUMBER(5)    NOT NULL,
    unit_price NUMBER(10,2) NOT NULL,
    line_total NUMBER(12,2) GENERATED ALWAYS AS (quantity * unit_price) VIRTUAL,
    CONSTRAINT pk_order_items PRIMARY KEY (order_id, line_no),
    CONSTRAINT uq_order_items_product UNIQUE (order_id, product_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
        REFERENCES products (product_id),
    CONSTRAINT ck_order_items_qty CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price CHECK (unit_price >= 0)
);

CREATE TABLE payments (
    payment_id     NUMBER(12)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id       NUMBER(12)   NOT NULL,
    payment_method VARCHAR2(12) NOT NULL,
    amount         NUMBER(12,2) NOT NULL,
    status         VARCHAR2(10) NOT NULL,
    txn_reference  VARCHAR2(50),
    paid_at        TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT uq_payments_txn UNIQUE (txn_reference),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT ck_payments_method CHECK (payment_method IN ('UPI', 'CARD', 'WALLET', 'NETBANKING', 'COD')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);

CREATE TABLE shipments (
    shipment_id     NUMBER(12)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id        NUMBER(12)   NOT NULL,
    carrier         VARCHAR2(50) NOT NULL,
    tracking_number VARCHAR2(50) NOT NULL,
    status          VARCHAR2(12) NOT NULL,
    delivered_by    NUMBER(10),
    shipped_at      TIMESTAMP,
    delivered_at    TIMESTAMP,
    CONSTRAINT pk_shipments PRIMARY KEY (shipment_id),
    CONSTRAINT uq_shipments_order UNIQUE (order_id),
    CONSTRAINT uq_shipments_tracking UNIQUE (tracking_number),
    CONSTRAINT fk_shipments_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT fk_shipments_employee FOREIGN KEY (delivered_by)
        REFERENCES employees (employee_id),
    CONSTRAINT ck_shipments_status CHECK (status IN ('CREATED', 'IN_TRANSIT', 'DELIVERED', 'FAILED')),
    CONSTRAINT ck_shipments_dates CHECK (delivered_at IS NULL OR delivered_at >= shipped_at)
);

CREATE TABLE returns (
    return_id     NUMBER(12)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id      NUMBER(12)    NOT NULL,
    line_no       NUMBER(4)     NOT NULL,
    quantity      NUMBER(5)     NOT NULL,
    reason        VARCHAR2(200) NOT NULL,
    status        VARCHAR2(10)  DEFAULT 'REQUESTED' NOT NULL,
    refund_amount NUMBER(12,2)  NOT NULL,
    requested_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_returns PRIMARY KEY (return_id),
    CONSTRAINT fk_returns_order_item FOREIGN KEY (order_id, line_no)
        REFERENCES order_items (order_id, line_no),
    CONSTRAINT ck_returns_status CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'REFUNDED')),
    CONSTRAINT ck_returns_qty CHECK (quantity > 0),
    CONSTRAINT ck_returns_refund CHECK (refund_amount >= 0)
);

CREATE TABLE reviews (
    review_id   NUMBER(12)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    product_id  NUMBER(10)     NOT NULL,
    customer_id NUMBER(10)     NOT NULL,
    rating      NUMBER(1)      NOT NULL,
    review_text VARCHAR2(1000),
    created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reviews PRIMARY KEY (review_id),
    CONSTRAINT uq_reviews_product_customer UNIQUE (product_id, customer_id),
    CONSTRAINT fk_reviews_product FOREIGN KEY (product_id)
        REFERENCES products (product_id),
    CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

-- ---------- Audit ------------------------------------------------------------

CREATE TABLE audit_log (
    audit_id   NUMBER(15)     GENERATED ALWAYS AS IDENTITY,
    table_name VARCHAR2(128)  NOT NULL,
    operation  VARCHAR2(6)    NOT NULL,
    pk_value   VARCHAR2(200)  NOT NULL,
    old_values VARCHAR2(4000),
    new_values VARCHAR2(4000),
    changed_by VARCHAR2(128)  DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
    changed_at TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_id),
    CONSTRAINT ck_audit_log_op CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- ---------- Indexes ----------------------------------------------------------
-- Primary key and unique constraints already create indexes.
-- Oracle does NOT index foreign key columns automatically. Index the ones that
-- are joined or filtered on, and the ones whose parent rows are deleted/updated
-- (otherwise the child table is locked during the parent DML).

CREATE INDEX ix_categories_parent    ON categories (parent_category_id);
CREATE INDEX ix_products_category    ON products (category_id);
CREATE INDEX ix_products_supplier    ON products (supplier_id);
CREATE INDEX ix_products_name_upper  ON products (UPPER(product_name));
CREATE INDEX ix_employees_manager    ON employees (manager_id);
CREATE INDEX ix_employees_warehouse  ON employees (warehouse_id);
CREATE INDEX ix_addresses_customer   ON addresses (customer_id);
CREATE INDEX ix_inventory_product    ON inventory (product_id);
CREATE INDEX ix_stock_mov_wh_prod    ON stock_movements (warehouse_id, product_id, moved_at);
CREATE INDEX ix_carts_customer       ON carts (customer_id);
CREATE INDEX ix_cart_items_product   ON cart_items (product_id);
CREATE INDEX ix_coupons_promotion    ON coupons (promotion_id);
CREATE INDEX ix_orders_cust_date     ON orders (customer_id, order_date DESC);
CREATE INDEX ix_orders_status_date   ON orders (status, order_date);
CREATE INDEX ix_orders_address       ON orders (address_id);
CREATE INDEX ix_orders_warehouse     ON orders (warehouse_id);
CREATE INDEX ix_orders_coupon        ON orders (coupon_id);
CREATE INDEX ix_order_items_product  ON order_items (product_id);
CREATE INDEX ix_payments_order       ON payments (order_id);
CREATE INDEX ix_shipments_employee   ON shipments (delivered_by);
CREATE INDEX ix_returns_order_item   ON returns (order_id, line_no);
CREATE INDEX ix_reviews_customer     ON reviews (customer_id);
CREATE INDEX ix_audit_log_tab_time   ON audit_log (table_name, changed_at);

-- ---------- Comments (data dictionary documentation) -------------------------

COMMENT ON TABLE orders IS 'One row per customer order. total_amount = subtotal - discount_amount + delivery_fee.';
COMMENT ON COLUMN orders.status IS 'PLACED -> PACKED -> SHIPPED -> DELIVERED, or CANCELLED before shipping.';
COMMENT ON TABLE inventory IS 'Stock per warehouse and product. Available = qty_on_hand - qty_reserved.';
COMMENT ON COLUMN order_items.unit_price IS 'Price at the time of the order (snapshot), not the current catalog price.';
